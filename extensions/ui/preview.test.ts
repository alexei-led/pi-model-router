import { expect, it } from 'vitest';
import { normalizeConfig } from '../config';
import { model, required } from '../test/fixtures';
import { ROUTER_ACTIVITIES, ROUTER_MODES } from '../types';
import { routePreferences } from './preview';

const find = (provider: string, id: string) =>
  model(id, {
    provider,
    contextWindow: 1_000_000,
    thinkingLevelMap: { xhigh: 'xhigh', max: 'max' },
    cost: {
      input:
        id === 'gpt-6-luna' || id === 'claude-haiku-5-5'
          ? 0.1
          : id === 'claude-opus-5-5'
            ? 4
            : 2,
      output: 10,
      cacheRead: 0.1,
      cacheWrite: 1,
    },
  });
const pairs = {
  openai: ['gpt-6-luna', 'gpt-6-luna', 'gpt-6.1-sol', 'gpt-6.1-sol'],
  anthropic: [
    'claude-haiku-5-5',
    'claude-haiku-5-5',
    'claude-opus-5-5',
    'claude-opus-5-5',
  ],
} as const;

it('matches every mode preference for all 56 built-in activity cells', async () => {
  const lines = [
    '# Mode preferences for activity presets',
    '',
    'Generated by `extensions/ui/preview.test.ts`. Do not edit by hand.',
    'Text-only, balanced-configured profiles. All targets are available and fit the request.',
    'Pins, effort overrides, soft-budget changes, live advice, cache holds and recovery are not applied here.',
    'These are preferred pairs, not measured quality, cost or actual generation guarantees.',
    'See [routing modes](routing-modes.md) for controls, precedence and recovery.',
    '',
  ];
  for (const family of ['openai', 'anthropic'] as const) {
    const ids = pairs[family];
    const profile = required(
      normalizeConfig({
        profiles: {
          p: {
            micro: { model: `preview/${ids[0]}`, thinking: 'low' },
            low: { model: `preview/${ids[1]}`, thinking: 'high' },
            medium: { model: `preview/${ids[2]}`, thinking: 'medium' },
            high: { model: `preview/${ids[3]}`, thinking: 'high' },
          },
        },
      }).config.profiles.p,
    );
    const preferences = ROUTER_MODES.map((mode) =>
      routePreferences({
        profile,
        find,
        mode: { mode, source: 'profile' },
        pin: 'auto',
        thinkingOverrides: {},
        activityRouting: true,
        budgetExceeded: false,
      }),
    );
    lines.push(
      `## ${family}`,
      '',
      '| Activity | Tier | cost | balanced | quality |',
      '| --- | --- | --- | --- | --- |',
    );
    for (const activity of ROUTER_ACTIVITIES)
      for (const tier of ['micro', 'low', 'medium', 'high'] as const) {
        const values = preferences.map((preferred) => {
          const result = preferred(activity, tier);
          expect(result.status).toBe('eligible');
          const route = required(result.route);
          return `${route.model.split('/')[1]} / ${route.thinking}`;
        });
        lines.push(`| ${activity} | ${tier} | ${values.join(' | ')} |`);
      }
    lines.push('');
  }
  await expect(lines.join('\n')).toMatchFileSnapshot(
    '../../docs/mode-preferences.md',
  );
});

it('distinguishes unknown registry, missing routes and an explicit fallback', () => {
  const profile = required(
    normalizeConfig({
      profiles: {
        p: {
          activityPreset: 'off',
          medium: {
            model: 'preview/primary',
            thinking: 'high',
            fallbacks: ['preview/fallback'],
          },
        },
      },
    }).config.profiles.p,
  );
  const base = {
    profile,
    mode: { mode: 'balanced' as const, source: 'profile' as const },
    pin: 'auto' as const,
    thinkingOverrides: {},
    activityRouting: true,
    budgetExceeded: false,
  };
  expect(
    routePreferences({ ...base, find: undefined })('code', 'medium'),
  ).toMatchObject({ status: 'unknown' });
  expect(
    routePreferences({ ...base, find: () => undefined })('code', 'medium'),
  ).toMatchObject({ status: 'unavailable' });
  expect(
    routePreferences({
      ...base,
      find: (provider, id) =>
        id === 'primary' ? undefined : find(provider, id),
    })('code', 'medium'),
  ).toMatchObject({
    status: 'eligible',
    route: { model: 'preview/fallback' },
    fallback: true,
  });
  expect(
    routePreferences({ ...base, find, activityRouting: false })(
      'code',
      'medium',
    ),
  ).toMatchObject({
    bypass: 'activity-off',
    route: { model: 'preview/primary' },
  });
});
